assert.throws(()=>m.moveNode(initial,'e-crm','e-erp'),/not allowed/);
assert.throws(()=>m.moveNode(initial,'p-doc','e-crm'),/Invalid destination/);
const renamed=m.renameNode(initial,'p-private','Private Files');assert.equal(renamed.find(n=>n.id==='p-private').name,'Private Files');
