import ts from 'typescript';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const code=ts.transpileModule(readFileSync(new URL('../src/core/documentsModel.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const obj={exports:{}};new Function('exports','module',code)(obj.exports,obj);const m=obj.exports;
const initial=m.initialDocuments;
assert.equal(initial.filter(n=>n.drive==='personal'&&n.kind==='folder'&&n.parent===null).length,4);
assert.equal(m.visibleChildren(initial,'personal',null).length,4);
assert.equal(m.visibleChildren(initial,'personal','p-doc').length,2);
assert.equal(m.visibleChildren(initial,'enterprise',null).filter(n=>n.kind==='folder').length,6);
assert.equal(m.quotaUsage(initial,'personal'),397048);
assert.equal(m.bytesLabel(2048),'2.0 KB');
const moved=m.moveNode(initial,'p-note','p-proj');assert.equal(moved.find(n=>n.id==='p-note').parent,'p-proj');assert.equal(initial.find(n=>n.id==='p-note').parent,'p-private');
