assert.throws(()=>m.renameNode(initial,'p-private','bad/name'),/Invalid filename/);
const trashed=m.cascadeTrash(initial,'p-doc',true);assert.ok(trashed.find(n=>n.id==='p-note').isTrashed);assert.ok(trashed.find(n=>n.id==='p-private').isTrashed);assert.equal(m.cascadeTrash(trashed,'p-doc',false).find(n=>n.id==='p-note').isTrashed,false);
assert.equal(m.safeDocumentsParse('not-json'),initial);
assert.deepEqual(m.safeDocumentsParse(JSON.stringify(initial)),initial);
console.log('PASS: V28 document model tree, tenant-like drive partitions, quota, move rules, rename, recursive trash and metadata parse.');
